"""
Ошибки самого фреймворка, а не тестируемого приложения.

Отделены от обычных падений шага намеренно: опечатка в конструкторе — это сломанный
манифест, и её нельзя гасить ни retry, ни failsafe, ни continue_on_failure. Иначе
прогон зеленеет на шагах, которых не было.
"""


class WiredError(Exception):
    """Манифест нельзя выполнить: неизвестный keyword, битый конструктор, неверная арность."""


class ZapApiError(RuntimeError):
    """Неуспешный ответ ZAP API (4xx/5xx при validate=True у обёртки zapv2)."""
