# -*- coding: utf-8 -*-
"""Generate docs/cbr/letterheadData.ts from brand pack letterhead asset."""
import base64
from pathlib import Path

root = Path(__file__).resolve().parent
# Канон: D10 horizontal RU gray из официального пака (пропорции PNG точнее SVG viewBox).
candidates = [
    root
    / "assets"
    / "diameter_10_and_more"
    / "diameter_10andmore-horizontal-russian-png"
    / "logos_ru"
    / "logos"
    / "png"
    / "gray"
    / "horizontal"
    / "10andmore.png",
    root / "assets" / "letterhead-logo.png",
    root / "assets" / "letterhead-logo.svg",
]

src = next((p for p in candidates if p.is_file()), None)
if src is None:
    raise SystemExit("no letterhead asset found under docs/cbr/assets")

raw = src.read_bytes()
b64 = base64.b64encode(raw).decode("ascii")
mime = "image/svg+xml" if src.suffix.lower() == ".svg" else "image/png"
out = root / "letterheadData.ts"
out.write_text(
    "/** Letterhead data-URI. Generated by _gen_letterhead.py from brand pack "
    f"({src.relative_to(root).as_posix()}, spaceport). */\n"
    f'export const letterheadLogoDataUri =\n  "data:{mime};base64,{b64}";\n',
    encoding="utf-8",
)
# зеркало для короткого пути
mirror = root / "assets" / "letterhead-logo.png"
if src.resolve() != mirror.resolve() and mime == "image/png":
    mirror.write_bytes(raw)
print(f"wrote {out} ({out.stat().st_size} bytes) from {src.relative_to(root)}")
